//! Where the climate model gets its torus axes.
//!
//! [`noise::Axis::at`] runs two Bhaskara sines and two `turn_of` divisions per
//! circle, the climate model samples four circles per noise call, and a tile
//! needs six to nine noise calls. That trig is the single most expensive thing
//! in chunk generation, and it depends on nothing but `(tile, frequency)`.
//!
//! [`ChunkAxes`] pays for it once per chunk column and once per chunk row;
//! [`Axes::Direct`] computes it on the spot for the one-off queries (the home
//! search, a test, the bench). Both arms hand the field formulas the same
//! integers, so a chunk generated through the table is bit-identical to one
//! generated through the fallback -- which is what lets the generator get faster
//! without a single generated byte moving.

use oc_iso::grid::{MAP_H, MAP_W};
use oc_iso::torus::{rem_euclid, CHUNK};

use super::noise;
use super::{
    COAL_FIELD_FREQ, COAL_SCATTER_FREQ, CRYSTAL_FREQ, ELEV_CONTINENT_FREQ, ELEV_DETAIL_FREQ,
    ELEV_HILL_FREQ, HUMIDITY_FINE_FREQ, HUMIDITY_FREQ, ORE_FIELD_FREQ, ORE_SCATTER_FREQ,
    TEMP_NOISE_FREQ,
};

/// Frequencies the climate model samples, in axis-table slot order.
const AXIS_FREQS: [i32; 11] = [
    ELEV_CONTINENT_FREQ,
    ELEV_HILL_FREQ,
    ELEV_DETAIL_FREQ,
    TEMP_NOISE_FREQ,
    HUMIDITY_FREQ,
    HUMIDITY_FINE_FREQ,
    CRYSTAL_FREQ,
    ORE_FIELD_FREQ,
    COAL_FIELD_FREQ,
    ORE_SCATTER_FREQ,
    COAL_SCATTER_FREQ,
];

/// Slot of a frequency in [`AXIS_FREQS`].
///
/// Every call site passes one of the constants above, so this folds away. The
/// `unreachable` is the guard against adding a field that reads a frequency the
/// table does not carry: that would silently sample a different planet.
#[inline]
#[must_use]
fn slot(freq: i32) -> usize {
    match freq {
        ELEV_CONTINENT_FREQ => 0,
        ELEV_HILL_FREQ => 1,
        ELEV_DETAIL_FREQ => 2,
        TEMP_NOISE_FREQ => 3,
        HUMIDITY_FREQ => 4,
        HUMIDITY_FINE_FREQ => 5,
        CRYSTAL_FREQ => 6,
        ORE_FIELD_FREQ => 7,
        COAL_FIELD_FREQ => 8,
        ORE_SCATTER_FREQ => 9,
        COAL_SCATTER_FREQ => 10,
        _ => unreachable!("frequency has no axis slot"),
    }
}

/// Axis samples for one chunk: one per column, one per row, per frequency.
#[derive(Clone, Copy, Debug)]
pub struct ChunkAxes {
    ox: i32,
    oy: i32,
    cols: [[noise::Axis; CHUNK as usize]; AXIS_FREQS.len()],
    rows: [[noise::Axis; CHUNK as usize]; AXIS_FREQS.len()],
}

impl ChunkAxes {
    /// Precompute the trig for the chunk whose north-west tile is `(ox, oy)`.
    #[must_use]
    pub fn new(ox: i32, oy: i32) -> Self {
        let mut cols = [[noise::Axis::default(); CHUNK as usize]; AXIS_FREQS.len()];
        let mut rows = [[noise::Axis::default(); CHUNK as usize]; AXIS_FREQS.len()];
        for (i, &freq) in AXIS_FREQS.iter().enumerate() {
            for l in 0..CHUNK as usize {
                cols[i][l] = noise::Axis::at(ox + l as i32, MAP_W, freq);
                rows[i][l] = noise::Axis::at(oy + l as i32, MAP_H, freq);
            }
        }
        Self { ox, oy, cols, rows }
    }

    /// Column sample: the trig paid once for this x.
    #[inline]
    #[must_use]
    fn column(&self, freq: i32, tile: i32) -> noise::Axis {
        self.cols[slot(freq)][rem_euclid(tile - self.ox, CHUNK) as usize]
    }

    /// Row sample: the trig paid once for this y.
    #[inline]
    #[must_use]
    fn row(&self, freq: i32, tile: i32) -> noise::Axis {
        self.rows[slot(freq)][rem_euclid(tile - self.oy, CHUNK) as usize]
    }
}

/// Where the climate model reads its torus axes from.
#[derive(Clone, Copy, Debug)]
pub enum Axes<'a> {
    /// Per-chunk table: the trig is already paid for.
    Chunk(&'a ChunkAxes),
    /// One tile at a time: the reference path.
    Direct,
}

impl Axes<'_> {
    /// Axis sample for the x circle at a tile coordinate.
    #[inline]
    #[must_use]
    pub fn axis_x(&self, freq: i32, tile: i32) -> noise::Axis {
        match self {
            Self::Chunk(table) => table.column(freq, tile),
            Self::Direct => noise::Axis::at(tile, MAP_W, freq),
        }
    }

    /// Axis sample for the y circle at a tile coordinate.
    #[inline]
    #[must_use]
    pub fn axis_y(&self, freq: i32, tile: i32) -> noise::Axis {
        match self {
            Self::Chunk(table) => table.row(freq, tile),
            Self::Direct => noise::Axis::at(tile, MAP_H, freq),
        }
    }
}
