//! The native APHELION window: tao for the shell, wry/WebView2 for the client.
//!
//! The page is served from the embedded `dist/` table through the `aphelion`
//! custom protocol. There is deliberately no loopback HTTP listener on this
//! path: closing the window closes the game, and the client cannot be reached
//! from a browser tab.
//!
//! `run` only returns when window creation or WebView creation fails, or when
//! the event loop exits. The caller uses the `Err` case to fall back to the
//! browser launcher with a human-readable reason.

use std::path::PathBuf;

use tao::dpi::{LogicalPosition, LogicalSize};
use tao::event::{Event, WindowEvent};
use tao::event_loop::{ControlFlow, EventLoop};
use tao::window::{Icon, WindowBuilder};
use wry::{PageLoadEvent, WebContext, WebViewBuilder};

use crate::protocol;

/// The 64x64 RGBA mark generated by `node scripts/gen-icon.mjs`.
const ICON_RGBA: &[u8] = include_bytes!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../assets/icon.rgba"
));
const ICON_SIZE: u32 = 64;

const INITIAL_WIDTH: f64 = 1600.0;
const INITIAL_HEIGHT: f64 = 900.0;
const MIN_WIDTH: f64 = 1024.0;
const MIN_HEIGHT: f64 = 640.0;

/// 创建窗口并进入事件循环。
///
/// `query` 会原样传给页面，使 `--seed` / `--debug` 与网页版（`?seed=N`、
/// `?debug=1`）语义一致。窗口标题的版本号来自 `oc_protocol::PRODUCT_VERSION`，
/// 不存在第二处硬编码；构建戳来自 `build.rs` 注入的编译期常量，凭空认出
/// 手里这个 exe 是哪一天哪一分钟编出来的。
pub fn run(query: &str) -> Result<(), String> {
    let event_loop = EventLoop::new();
    let title = format!(
        "APHELION · 远日点 {}{suffix}",
        oc_protocol::PRODUCT_VERSION,
        suffix = build_stamp_suffix(),
    );
    let icon = Icon::from_rgba(ICON_RGBA.to_vec(), ICON_SIZE, ICON_SIZE).ok();
    let position = centered_position(&event_loop);

    let window = WindowBuilder::new()
        .with_title(title.clone())
        .with_inner_size(LogicalSize::new(INITIAL_WIDTH, INITIAL_HEIGHT))
        .with_min_inner_size(LogicalSize::new(MIN_WIDTH, MIN_HEIGHT))
        .with_resizable(true)
        .with_window_icon(icon)
        .with_position(position)
        .build(&event_loop)
        .map_err(|error| format!("窗口创建失败: {error}"))?;
    crate::info(&format!("  窗口已创建：{title}"));

    let url = protocol::initial_url(query);
    // Pin WebView2's user data directory (cache, cookies, localStorage) to
    // `%LOCALAPPDATA%\APHELION\WebView2`. Left to itself, WebView2 puts it in
    // `<exe name>.WebView2\` next to the executable: that directory is not
    // writable when the app is installed under `Program Files` (WebView2
    // creation then fails outright), and even from a writable folder it litters
    // the install directory with data the app should keep in the user profile.
    // A missing variable or an uncreatable directory falls back to the WebView2
    // default rather than failing the launch.
    let data_directory = webview_data_directory();
    let mut web_context = WebContext::new(data_directory.clone());
    let webview = WebViewBuilder::new_with_web_context(&mut web_context)
        .with_custom_protocol(protocol::SCHEME.to_string(), |_id, request| {
            protocol::respond(&request)
        })
        .with_url(&url)
        .with_background_color((0x0a, 0x11, 0x13, 0xff))
        .with_devtools(cfg!(debug_assertions))
        .with_navigation_handler(|target| protocol::navigation_allowed(&target))
        .with_on_page_load_handler(|event, loaded| match event {
            PageLoadEvent::Started => crate::info(&format!("  页面开始加载：{loaded}")),
            PageLoadEvent::Finished => crate::info(&format!("  页面加载完成：{loaded}")),
        })
        .build(&window)
        .map_err(|error| format!("WebView 创建失败: {error}"))?;
    if let Some(data_directory) = &data_directory {
        crate::info(&format!(
            "  WebView2 用户数据目录：{}",
            data_directory.display()
        ));
    }
    crate::info(&format!("  WebView 创建成功，加载：{url}"));

    // Keep the WebView alive for the whole event loop; dropping it would tear
    // down the WebView2 controller while the window is still visible. The
    // `WebContext` stays in scope just as long: it owns the user data directory
    // and must outlive the WebView that was built from it.
    let _webview = webview;
    event_loop.run(move |event, _, control_flow| {
        *control_flow = ControlFlow::Wait;
        if let Event::WindowEvent {
            event: WindowEvent::CloseRequested,
            ..
        } = event
        {
            *control_flow = ControlFlow::Exit;
        }
    });
}

/// Resolve the WebView2 user data directory to `%LOCALAPPDATA%\APHELION\WebView2`.
///
/// WebView2 defaults to `<exe name>.WebView2\` beside the executable, which is
/// wrong for a shipped app: the install directory is read-only under
/// `Program Files` (WebView2 creation fails) and even elsewhere it leaves a
/// cache directory next to the exe. See the call site in `run` for the details.
///
/// `None` on any failure — the caller then keeps WebView2's default directory
/// and the app still starts, which is the pre-fix behavior.
fn webview_data_directory() -> Option<PathBuf> {
    let Some(local_app_data) = std::env::var_os("LOCALAPPDATA").filter(|path| !path.is_empty())
    else {
        eprintln!("[desktop] 未找到 LOCALAPPDATA，WebView2 使用默认用户数据目录。");
        return None;
    };
    let data_directory = PathBuf::from(local_app_data)
        .join("APHELION")
        .join("WebView2");
    if let Err(error) = std::fs::create_dir_all(&data_directory) {
        eprintln!(
            "[desktop] 无法创建 WebView2 用户数据目录 {}: {error}；改用默认目录。",
            data_directory.display()
        );
        return None;
    }
    Some(data_directory)
}

/// Title-bar suffix for the build stamp: ` · 1022-1120`, or nothing.
///
/// `build.rs` injects `OC_BUILD_STAMP` as `2026-10-22 11:20` (local time). Title bars
/// are tight, so the suffix keeps only month-day and hour-minute. A build
/// without the variable (non-Windows) simply shows no suffix.
fn build_stamp_suffix() -> String {
    let stamp = option_env!("OC_BUILD_STAMP").unwrap_or("");
    let mut fields = stamp.split([' ', '-', ':']);
    let (Some(_), Some(month), Some(day), Some(hour), Some(minute)) = (
        fields.next(),
        fields.next(),
        fields.next(),
        fields.next(),
        fields.next(),
    ) else {
        return String::new();
    };
    format!(" · {month}{day}-{hour}{minute}")
}

/// Center the initial window on the primary monitor.
///
/// Works in logical pixels because `WindowBuilder::with_position` expects
/// logical coordinates on Windows. Negative offsets are clamped to the monitor
/// origin so a smaller-than-requested screen still shows the title bar.
fn centered_position(event_loop: &EventLoop<()>) -> LogicalPosition<f64> {
    let Some(monitor) = event_loop.primary_monitor() else {
        return LogicalPosition::new(80.0, 80.0);
    };
    let scale = monitor.scale_factor();
    let origin = monitor.position().to_logical::<f64>(scale);
    let size = monitor.size().to_logical::<f64>(scale);
    LogicalPosition::new(
        origin.x + ((size.width - INITIAL_WIDTH) / 2.0).max(0.0),
        origin.y + ((size.height - INITIAL_HEIGHT) / 2.0).max(0.0),
    )
}
