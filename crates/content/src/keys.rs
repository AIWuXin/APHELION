//! Key arrays mirrored into TypeScript.
//!
//! `web/src/generated/content-keys.ts` is written by the `codegen` test below,
//! so the union types used by the render registry can never drift from the
//! Rust tables. Adding a building therefore forces a TypeScript compile error
//! until the matching painter is registered.

use crate::{buildings, events, routes, techs, terrain, units};

/// Keys of the building table, in wire order.
#[must_use]
pub fn building_keys() -> Vec<&'static str> {
    buildings::BUILDINGS.iter().map(|r| r.key).collect()
}

/// Keys of the unit table, in wire order.
#[must_use]
pub fn unit_keys() -> Vec<&'static str> {
    units::UNITS.iter().map(|r| r.key).collect()
}

/// Keys of the route table.
#[must_use]
pub fn route_keys() -> Vec<&'static str> {
    routes::ROUTES.iter().map(|r| r.key).collect()
}

/// Keys of the event table.
#[must_use]
pub fn event_keys() -> Vec<&'static str> {
    events::EVENTS.iter().map(|r| r.key).collect()
}

/// Keys of the tech table.
#[must_use]
pub fn tech_keys() -> Vec<&'static str> {
    techs::TECHS.iter().map(|r| r.key).collect()
}

/// Keys of the terrain material table.
#[must_use]
pub fn terrain_keys() -> Vec<&'static str> {
    terrain::TERRAIN.iter().map(|r| r.key).collect()
}

/// Keys of the decoration table.
#[must_use]
pub fn decor_keys() -> Vec<&'static str> {
    terrain::DECOR.iter().map(|r| r.key).collect()
}

/// Effect keys, indexed by `oc_protocol::snapshot::EFFECT_*`.
pub const EFFECT_KEYS: &[&str] = &[
    "muzzle", "impact", "explode", "trail", "flare", "pop", "spark",
];

/// Beam keys, indexed by `oc_protocol::snapshot::BEAM_*`.
pub const BEAM_KEYS: &[&str] = &["rail", "flak", "cannon", "lance", "tractor", "repair"];

/// HUD tab keys for the 2x2 category selector.
pub const CATEGORY_KEYS: &[&str] = &["build", "orbital", "defence", "support"];

/// Chinese labels for the category tabs.
pub const CATEGORY_LABELS_ZH: &[&str] = &["基建", "轨道", "防务", "保障"];

/// Unit layer keys.
pub const LAYER_KEYS: &[&str] = &["ground", "air", "orbit"];

/// Helper: `["a", "b"]` literal for a `&[&str]`.
fn ts_array(items: &[&str]) -> String {
    let body = items
        .iter()
        .map(|k| format!("\"{k}\""))
        .collect::<Vec<_>>()
        .join(", ");
    format!("[{body}]")
}

/// Render the generated TypeScript module as a string.
#[must_use]
pub fn render_ts() -> String {
    let mut out = String::new();
    out.push_str("// AUTO-GENERATED by `cargo test -p oc-content`. Do not edit.\n");
    out.push_str("// Source of truth: crates/content/src/{buildings,units,routes,techs,events,terrain}.rs\n\n");

    for (const_name, keys) in [
        ("BUILDING_KEYS", building_keys()),
        ("UNIT_KEYS", unit_keys()),
        ("ROUTE_KEYS", route_keys()),
        ("TECH_KEYS", tech_keys()),
        ("EVENT_KEYS", event_keys()),
        ("TERRAIN_KEYS", terrain_keys()),
        ("DECOR_KEYS", decor_keys()),
    ] {
        let ty = const_name.trim_end_matches("_KEYS");
        let ty = format!("{}{}", &ty[..1], ty[1..].to_ascii_lowercase());
        let ty = ty
            .split('_')
            .map(|p| {
                let mut c = p.chars();
                match c.next() {
                    Some(f) => format!("{}{}", f.to_ascii_uppercase(), c.as_str()),
                    None => String::new(),
                }
            })
            .collect::<String>();
        out.push_str(&format!(
            "export const {const_name} = {} as const;\n",
            ts_array(&keys)
        ));
        out.push_str(&format!(
            "export type {ty}Key = (typeof {const_name})[number];\n\n"
        ));
    }

    out.push_str(&format!(
        "export const EFFECT_KEYS = {} as const;\n",
        ts_array(EFFECT_KEYS)
    ));
    out.push_str("export type EffectKey = (typeof EFFECT_KEYS)[number];\n\n");
    out.push_str(&format!(
        "export const BEAM_KEYS = {} as const;\n",
        ts_array(BEAM_KEYS)
    ));
    out.push_str("export type BeamKey = (typeof BEAM_KEYS)[number];\n\n");
    out.push_str(&format!(
        "export const CATEGORY_KEYS = {} as const;\n",
        ts_array(CATEGORY_KEYS)
    ));
    out.push_str("export type CategoryKey = (typeof CATEGORY_KEYS)[number];\n\n");
    out.push_str(&format!(
        "export const CATEGORY_LABELS_ZH = {} as const;\n",
        ts_array(CATEGORY_LABELS_ZH)
    ));
    out.push_str(&format!(
        "export const LAYER_KEYS = {} as const;\n",
        ts_array(LAYER_KEYS)
    ));
    out.push_str("export type LayerKey = (typeof LAYER_KEYS)[number];\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keys_are_unique_and_non_empty() {
        for keys in [
            building_keys(),
            unit_keys(),
            route_keys(),
            tech_keys(),
            event_keys(),
            terrain_keys(),
            decor_keys(),
        ] {
            assert!(!keys.is_empty());
            let mut sorted = keys.clone();
            sorted.sort_unstable();
            sorted.dedup();
            assert_eq!(sorted.len(), keys.len(), "duplicate key found in {keys:?}");
            for k in keys {
                assert!(!k.is_empty());
                assert!(
                    k.chars()
                        .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-'),
                    "key must be kebab-case: {k}"
                );
            }
        }
    }

    #[test]
    fn wire_order_matches_table_order() {
        assert_eq!(building_keys().len(), buildings::B_COUNT as usize);
        assert_eq!(unit_keys().len(), units::U_COUNT as usize);
        assert_eq!(route_keys().len(), routes::R_COUNT as usize);
        assert_eq!(terrain_keys().len(), terrain::T_COUNT as usize);
        assert_eq!(decor_keys().len(), terrain::D_COUNT as usize);
        assert_eq!(event_keys().len(), 14);
    }

    #[test]
    fn codegen_writes_content_keys_ts() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("..")
            .join("..")
            .join("web")
            .join("src")
            .join("generated");
        std::fs::create_dir_all(&dir).expect("create generated dir");
        std::fs::write(dir.join("content-keys.ts"), render_ts()).expect("write content-keys.ts");
    }
}
